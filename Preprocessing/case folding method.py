# metode python case folding
# lower() -> mengubah teks menjadi huruf kecil
# upper() -> mengubah teks menjadi huruf besar
# capitalize() -> mengubah teks menjadi huruf besar di awal kalimat
# title() -> mengubah teks menjadi huruf besar di awal setiap kata
# swapcase() -> mengubah teks menjadi huruf besar di awal setiap kata dan huruf kecil di awal setiap kata

teks = "Presiden Joko Widodo mengunjungi Universitas Indonesia Depok di hari Senin"
print(teks.lower())
print(teks.upper())
print(teks.capitalize())
print(teks.title())
print(teks.swapcase())